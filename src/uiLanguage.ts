export type UiText = keyof typeof englishText;

export function useUiLanguage() {
  const [params] = useSearchParams();
  const language = params.get("limba") === "en" ? "en" : "ro";
  const t = (text: string) => language === "en" && Object.hasOwn(englishText, text)
    ? englishText[text as UiText]
    : text;
  return { language, t };
}
