import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { readQuestionBanks } from "./question-bank-sources.mjs";

const banks = await readQuestionBanks();
const literal = value => "'" + String(value).replaceAll("'", "''") + "'";
let sql = "-- Generated by npm run supabase:export. Run this entire file in Supabase SQL Editor.\n";
sql += "begin;\nset local standard_conforming_strings = on;\n";
sql += readFileSync(new URL("../supabase/schema.sql", import.meta.url), "utf8") + "\n";
for (const { category, language, questions } of banks) {
  for (let offset = 0; offset < questions.length; offset += 100) {
    const rows = questions.slice(offset, offset + 100).map(q =>
      `(${[category, language, q.id, q.sourceNo, q.text, JSON.stringify(q.answers), q.correct, JSON.stringify(q.images ?? [])].map(literal).join(",")})`);
    sql += "insert into public.question_bank (category, language, id, source_no, text, answers, correct, images) values\n";
    sql += rows.join(",\n") + "\non conflict (category, language, id) do update set source_no = excluded.source_no, text = excluded.text, answers = excluded.answers, correct = excluded.correct, images = excluded.images;\n";
  }
  console.log(`${category}/${language}: ${questions.length}`);
}
sql += "commit;\nselect category, language, count(*) from public.question_bank group by category, language order by category, language;\n";
mkdirSync(new URL("../supabase/migrations/", import.meta.url), { recursive: true });
writeFileSync(new URL("../supabase/migrations/202610300001_question_banks.sql", import.meta.url), sql);
console.log("Migration generated. Existing matching questions are updated; unrelated rows are preserved.");
